-- =====================================================================
--  БД «Сотрудники высшего учебного заведения» (вариант 12)
--  Скрипт 1. Таблицы, ключи, ограничения
--  СУБД: PostgreSQL 14+
-- =====================================================================

SET client_encoding = 'UTF8';

DROP TABLE IF EXISTS телефон, сотрудник, тип_телефона, ученое_звание, ученая_степень,
                     должность, лаборатория, кафедра, факультет, отдел CASCADE;

-- ---------------------------------------------------------------------
--  Структура вуза: Отдел -> Факультет -> Кафедра -> Лаборатория
--  Первичные ключи генерируются последовательностями (IDENTITY)
-- ---------------------------------------------------------------------
CREATE TABLE отдел (
    номер_отдела      integer GENERATED BY DEFAULT AS IDENTITY,
    название_отдела   varchar(150) NOT NULL,
    CONSTRAINT pk_отдел PRIMARY KEY (номер_отдела),
    CONSTRAINT uq_отдел_название UNIQUE (название_отдела)
);

CREATE TABLE факультет (
    код_факультета      integer GENERATED BY DEFAULT AS IDENTITY,
    номер_отдела        integer NOT NULL,
    название_факультета varchar(150) NOT NULL,
    CONSTRAINT pk_факультет PRIMARY KEY (код_факультета),
    CONSTRAINT uq_факультет_название UNIQUE (название_факультета),
    CONSTRAINT fk_факультет_отдел FOREIGN KEY (номер_отдела)
        REFERENCES отдел (номер_отдела) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE кафедра (
    номер_кафедры     integer GENERATED BY DEFAULT AS IDENTITY,
    код_факультета    integer NOT NULL,
    название_кафедры  varchar(150) NOT NULL,
    CONSTRAINT pk_кафедра PRIMARY KEY (номер_кафедры),
    CONSTRAINT uq_кафедра_название UNIQUE (название_кафедры),
    CONSTRAINT fk_кафедра_факультет FOREIGN KEY (код_факультета)
        REFERENCES факультет (код_факультета) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE лаборатория (
    номер_лаборатории    integer GENERATED BY DEFAULT AS IDENTITY,
    номер_кафедры        integer NOT NULL,
    название_лаборатории varchar(150) NOT NULL,
    CONSTRAINT pk_лаборатория PRIMARY KEY (номер_лаборатории),
    CONSTRAINT uq_лаборатория_название UNIQUE (название_лаборатории),
    CONSTRAINT fk_лаборатория_кафедра FOREIGN KEY (номер_кафедры)
        REFERENCES кафедра (номер_кафедры) ON UPDATE CASCADE ON DELETE RESTRICT
);

-- ---------------------------------------------------------------------
--  Справочники
-- ---------------------------------------------------------------------
CREATE TABLE должность (
    код_должности       integer GENERATED BY DEFAULT AS IDENTITY,
    название_должности  varchar(100) NOT NULL,
    преподавательская   boolean NOT NULL DEFAULT false,  -- относится к ППС
    CONSTRAINT pk_должность PRIMARY KEY (код_должности),
    CONSTRAINT uq_должность_название UNIQUE (название_должности)
);

CREATE TABLE ученая_степень (
    код_степени       integer GENERATED BY DEFAULT AS IDENTITY,
    название_степени  varchar(100) NOT NULL,
    CONSTRAINT pk_ученая_степень PRIMARY KEY (код_степени),
    CONSTRAINT uq_ученая_степень_название UNIQUE (название_степени)
);

CREATE TABLE ученое_звание (
    код_звания       integer GENERATED BY DEFAULT AS IDENTITY,
    название_звания  varchar(100) NOT NULL,
    CONSTRAINT pk_ученое_звание PRIMARY KEY (код_звания),
    CONSTRAINT uq_ученое_звание_название UNIQUE (название_звания)
);

CREATE TABLE тип_телефона (
    код_типа       integer GENERATED BY DEFAULT AS IDENTITY,
    название_типа  varchar(50) NOT NULL,
    CONSTRAINT pk_тип_телефона PRIMARY KEY (код_типа),
    CONSTRAINT uq_тип_телефона_название UNIQUE (название_типа)
);

-- ---------------------------------------------------------------------
--  Личная карточка сотрудника
--  Сотрудник закреплён ровно за одним подразделением любого уровня
--  (отдел, факультет, кафедра или лаборатория).
-- ---------------------------------------------------------------------
CREATE TABLE сотрудник (
    табельный_номер         integer GENERATED BY DEFAULT AS IDENTITY,
    фамилия                 varchar(50)  NOT NULL,
    имя                     varchar(50)  NOT NULL,
    отчество                varchar(50),
    год_рождения            smallint     NOT NULL,
    код_должности           integer      NOT NULL,
    специальность_по_диплому varchar(150) NOT NULL,
    квалификация_по_диплому  varchar(100) NOT NULL,
    вуз_по_диплому          varchar(200),
    общий_стаж              smallint     NOT NULL DEFAULT 0,
    стаж_нпр                smallint     NOT NULL DEFAULT 0,   -- научно-педагогический стаж
    код_степени             integer,
    код_звания              integer,
    основное_место_работы   varchar(200) NOT NULL DEFAULT 'ИРНИТУ',
    номер_отдела            integer,
    код_факультета          integer,
    номер_кафедры           integer,
    номер_лаборатории       integer,
    CONSTRAINT pk_сотрудник PRIMARY KEY (табельный_номер),
    CONSTRAINT fk_сотрудник_должность FOREIGN KEY (код_должности)
        REFERENCES должность (код_должности) ON DELETE RESTRICT,
    CONSTRAINT fk_сотрудник_степень FOREIGN KEY (код_степени)
        REFERENCES ученая_степень (код_степени) ON DELETE RESTRICT,
    CONSTRAINT fk_сотрудник_звание FOREIGN KEY (код_звания)
        REFERENCES ученое_звание (код_звания) ON DELETE RESTRICT,
    CONSTRAINT fk_сотрудник_отдел FOREIGN KEY (номер_отдела)
        REFERENCES отдел (номер_отдела) ON DELETE RESTRICT,
    CONSTRAINT fk_сотрудник_факультет FOREIGN KEY (код_факультета)
        REFERENCES факультет (код_факультета) ON DELETE RESTRICT,
    CONSTRAINT fk_сотрудник_кафедра FOREIGN KEY (номер_кафедры)
        REFERENCES кафедра (номер_кафедры) ON DELETE RESTRICT,
    CONSTRAINT fk_сотрудник_лаборатория FOREIGN KEY (номер_лаборатории)
        REFERENCES лаборатория (номер_лаборатории) ON DELETE RESTRICT,
    CONSTRAINT ck_сотрудник_одно_подразделение CHECK (
        num_nonnulls(номер_отдела, код_факультета, номер_кафедры, номер_лаборатории) = 1),
    CONSTRAINT ck_сотрудник_стаж CHECK (общий_стаж >= 0 AND стаж_нпр >= 0 AND стаж_нпр <= общий_стаж)
);

CREATE TABLE телефон (
    код_телефона     integer GENERATED BY DEFAULT AS IDENTITY,
    табельный_номер  integer     NOT NULL,
    код_типа         integer     NOT NULL,
    номер            varchar(20) NOT NULL,
    CONSTRAINT pk_телефон PRIMARY KEY (код_телефона),
    CONSTRAINT fk_телефон_сотрудник FOREIGN KEY (табельный_номер)
        REFERENCES сотрудник (табельный_номер) ON DELETE CASCADE,
    CONSTRAINT fk_телефон_тип FOREIGN KEY (код_типа)
        REFERENCES тип_телефона (код_типа) ON DELETE RESTRICT,
    CONSTRAINT uq_телефон_сотрудник_номер UNIQUE (табельный_номер, номер)
);

-- Индексы по внешним ключам и для поиска
CREATE INDEX ix_факультет_отдел      ON факультет (номер_отдела);
CREATE INDEX ix_кафедра_факультет    ON кафедра (код_факультета);
CREATE INDEX ix_лаборатория_кафедра  ON лаборатория (номер_кафедры);
CREATE INDEX ix_сотрудник_фамилия    ON сотрудник (lower(фамилия));
CREATE INDEX ix_сотрудник_должность  ON сотрудник (код_должности);
CREATE INDEX ix_телефон_сотрудник    ON телефон (табельный_номер);
