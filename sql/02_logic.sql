-- 2.1 Все подразделения вуза единым списком (иерархия с полным путём)
CREATE OR REPLACE VIEW v_подразделение AS
SELECT 'отдел'::text AS тип, 1 AS уровень,
       'отдел:' || o.номер_отдела AS ключ, o.номер_отдела AS ид,
       o.название_отдела AS название,
       o.название_отдела AS путь,
       o.номер_отдела, NULL::int AS код_факультета, NULL::int AS номер_кафедры, NULL::int AS номер_лаборатории
FROM отдел o
UNION ALL
SELECT 'факультет', 2, 'факультет:' || f.код_факультета, f.код_факультета,
       f.название_факультета,
       o.название_отдела || ' / ' || f.название_факультета,
       o.номер_отдела, f.код_факультета, NULL, NULL
FROM факультет f JOIN отдел o ON o.номер_отдела = f.номер_отдела
UNION ALL
SELECT 'кафедра', 3, 'кафедра:' || k.номер_кафедры, k.номер_кафедры,
       k.название_кафедры,
       o.название_отдела || ' / ' || f.название_факультета || ' / ' || k.название_кафедры,
       o.номер_отдела, f.код_факультета, k.номер_кафедры, NULL
FROM кафедра k
JOIN факультет f ON f.код_факультета = k.код_факультета
JOIN отдел o     ON o.номер_отдела = f.номер_отдела
UNION ALL
SELECT 'лаборатория', 4, 'лаборатория:' || l.номер_лаборатории, l.номер_лаборатории,
       l.название_лаборатории,
       o.название_отдела || ' / ' || f.название_факультета || ' / ' || k.название_кафедры || ' / ' || l.название_лаборатории,
       o.номер_отдела, f.код_факультета, k.номер_кафедры, l.номер_лаборатории
FROM лаборатория l
JOIN кафедра k   ON k.номер_кафедры = l.номер_кафедры
JOIN факультет f ON f.код_факультета = k.код_факультета
JOIN отдел o     ON o.номер_отдела = f.номер_отдела;

-- 2.2 Полные сведения о сотруднике (с расшифровкой справочников,
--     подразделением, всей цепочкой вышестоящих подразделений и телефонами)
CREATE OR REPLACE VIEW v_сотрудник AS
SELECT s.табельный_номер,
       s.фамилия, s.имя, s.отчество,
       concat_ws(' ', s.фамилия, s.имя, s.отчество) AS фио,
       s.фамилия || ' ' || left(s.имя, 1) || '.' ||
           coalesce(' ' || left(s.отчество, 1) || '.', '') AS фио_кратко,
       s.год_рождения,
       extract(year FROM current_date)::int - s.год_рождения AS возраст,
       s.код_должности, d.название_должности AS должность, d.преподавательская,
       s.специальность_по_диплому, s.квалификация_по_диплому, s.вуз_по_диплому,
       s.общий_стаж, s.стаж_нпр,
       s.код_степени, st.название_степени AS ученая_степень,
       s.код_звания,  zv.название_звания  AS ученое_звание,
       s.основное_место_работы,
       p.тип AS тип_подразделения, p.ключ AS ключ_подразделения,
       p.название AS подразделение, p.путь AS путь_подразделения,
       p.номер_отдела AS отдел_ид, p.код_факультета AS факультет_ид,
       p.номер_кафедры AS кафедра_ид, p.номер_лаборатории AS лаборатория_ид,
       o.название_отдела AS отдел,
       (SELECT string_agg(tt.название_типа || ': ' || t.номер, '; ' ORDER BY tt.код_типа, t.код_телефона)
          FROM телефон t JOIN тип_телефона tt ON tt.код_типа = t.код_типа
         WHERE t.табельный_номер = s.табельный_номер) AS телефоны
FROM сотрудник s
JOIN должность d          ON d.код_должности = s.код_должности
LEFT JOIN ученая_степень st ON st.код_степени = s.код_степени
LEFT JOIN ученое_звание zv  ON zv.код_звания = s.код_звания
JOIN v_подразделение p ON p.ключ = CASE
        WHEN s.номер_лаборатории IS NOT NULL THEN 'лаборатория:' || s.номер_лаборатории
        WHEN s.номер_кафедры     IS NOT NULL THEN 'кафедра:'     || s.номер_кафедры
        WHEN s.код_факультета    IS NOT NULL THEN 'факультет:'   || s.код_факультета
        ELSE 'отдел:' || s.номер_отдела END
JOIN отдел o ON o.номер_отдела = p.номер_отдела;

