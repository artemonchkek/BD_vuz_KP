-- 4.1 Годовое начисление стажа: всем сотрудникам увеличивается общий
--     стаж, преподавателям — также научно-педагогический стаж
CREATE OR REPLACE PROCEDURE sp_начислить_стаж(p_лет int, INOUT p_обновлено int DEFAULT 0)
LANGUAGE plpgsql AS $$
BEGIN
    IF p_лет IS NULL OR p_лет < 1 OR p_лет > 5 THEN
        RAISE EXCEPTION 'Количество лет для начисления стажа должно быть от 1 до 5'
              USING ERRCODE = 'P0001', HINT = 'лет';
    END IF;
    UPDATE сотрудник s
       SET общий_стаж = s.общий_стаж + p_лет,
           стаж_нпр = s.стаж_нпр + CASE WHEN d.преподавательская THEN p_лет ELSE 0 END
      FROM должность d
     WHERE d.код_должности = s.код_должности;
    GET DIAGNOSTICS p_обновлено = ROW_COUNT;
END $$;

-- 4.2 Перевод сотрудника в другое подразделение (ключ вида 'кафедра:3')
CREATE OR REPLACE PROCEDURE sp_перевести_сотрудника(p_табельный int, p_ключ text)
LANGUAGE plpgsql AS $$
DECLARE
    v_тип text := split_part(p_ключ, ':', 1);
    v_ид  int  := nullif(split_part(p_ключ, ':', 2), '')::int;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM v_подразделение WHERE ключ = p_ключ) THEN
        RAISE EXCEPTION 'Подразделение не найдено' USING ERRCODE = 'P0001', HINT = 'подразделение';
    END IF;
    UPDATE сотрудник
       SET номер_отдела      = CASE WHEN v_тип = 'отдел'       THEN v_ид END,
           код_факультета    = CASE WHEN v_тип = 'факультет'   THEN v_ид END,
           номер_кафедры     = CASE WHEN v_тип = 'кафедра'     THEN v_ид END,
           номер_лаборатории = CASE WHEN v_тип = 'лаборатория' THEN v_ид END
     WHERE табельный_номер = p_табельный;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Сотрудник с табельным номером % не найден', p_табельный USING ERRCODE = 'P0001';
    END IF;
END $$;
