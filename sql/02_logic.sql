-- 3.1 Принадлежит ли сотрудник/подразделение поддереву выбранного
--     подразделения. p_ключ = 'тип:ид' или NULL (весь вуз)
CREATE OR REPLACE FUNCTION fn_в_подразделении(
    p_ключ text, p_отдел int, p_факультет int, p_кафедра int, p_лаборатория int)
RETURNS boolean LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE
    v_тип text;
    v_ид  int;
BEGIN
    IF p_ключ IS NULL OR p_ключ = '' THEN
        RETURN true;
    END IF;
    v_тип := split_part(p_ключ, ':', 1);
    v_ид  := nullif(split_part(p_ключ, ':', 2), '')::int;
    RETURN CASE v_тип
        WHEN 'отдел'       THEN p_отдел = v_ид
        WHEN 'факультет'   THEN p_факультет = v_ид
        WHEN 'кафедра'     THEN p_кафедра = v_ид
        WHEN 'лаборатория' THEN p_лаборатория = v_ид
        ELSE false END;
END $$;

-- 3.2 Выходной документ 1. Телефонный справочник:
--     подразделения, сотрудники каждого подразделения и их телефоны
CREATE OR REPLACE FUNCTION fn_телефонный_справочник(p_ключ text DEFAULT NULL)
RETURNS TABLE (
    путь text, подразделение text, тип text, уровень int,
    табельный_номер int, фио text, должность text, телефоны text)
LANGUAGE sql STABLE AS $$
    SELECT p.путь, p.название, p.тип, p.уровень,
           v.табельный_номер, v.фио, v.должность, v.телефоны
    FROM v_подразделение p
    LEFT JOIN v_сотрудник v ON v.ключ_подразделения = p.ключ
    WHERE fn_в_подразделении(p_ключ, p.номер_отдела, p.код_факультета, p.номер_кафедры, p.номер_лаборатории)
    ORDER BY p.путь, v.фамилия, v.имя, v.отчество;
$$;

-- 3.3 Выходной документ 2. Сотрудники, стаж работы которых
--     не превышает заданной цифры, упорядоченные по отделам
CREATE OR REPLACE FUNCTION fn_сотрудники_по_стажу(p_макс_стаж int, p_ключ text DEFAULT NULL)
RETURNS TABLE (
    отдел text, подразделение text, табельный_номер int, фио text,
    должность text, год_рождения smallint, общий_стаж smallint)
LANGUAGE plpgsql STABLE AS $$
BEGIN
    IF p_макс_стаж IS NULL OR p_макс_стаж < 0 OR p_макс_стаж > 70 THEN
        RAISE EXCEPTION 'Предельный стаж должен быть целым числом от 0 до 70 лет'
              USING ERRCODE = 'P0001', HINT = 'стаж';
    END IF;
    RETURN QUERY
    SELECT v.отдел::text, v.путь_подразделения::text, v.табельный_номер, v.фио::text,
           v.должность::text, v.год_рождения, v.общий_стаж
    FROM v_сотрудник v
    WHERE v.общий_стаж <= p_макс_стаж
      AND fn_в_подразделении(p_ключ, v.отдел_ид, v.факультет_ид, v.кафедра_ид, v.лаборатория_ид)
    ORDER BY v.отдел, v.путь_подразделения, v.общий_стаж, v.фио;
END $$;

-- 3.4 Выходной документ 3. Сведения о лицах с учёными степенями и
--     учёными званиями (по преподавательскому составу подразделения)
CREATE OR REPLACE FUNCTION fn_сведения_нпр(p_ключ text DEFAULT NULL, p_только_с_степенью boolean DEFAULT false)
RETURNS TABLE (
    табельный_номер int, фио text, вуз_специальность text, степень_звание text,
    стаж_нпр smallint, место_должность text, есть_степень_звание boolean)
LANGUAGE sql STABLE AS $$
    SELECT v.табельный_номер, v.фио,
           concat_ws(', ', v.вуз_по_диплому,
                     'специальность «' || v.специальность_по_диплому || '»',
                     'квалификация «' || v.квалификация_по_диплому || '»'),
           coalesce(nullif(concat_ws(', ', v.ученая_степень, v.ученое_звание), ''), '—'),
           v.стаж_нпр,
           v.основное_место_работы || ', ' || lower(v.должность),
           (v.код_степени IS NOT NULL OR v.код_звания IS NOT NULL)
    FROM v_сотрудник v
    WHERE v.преподавательская
      AND fn_в_подразделении(p_ключ, v.отдел_ид, v.факультет_ид, v.кафедра_ид, v.лаборатория_ид)
      AND (NOT p_только_с_степенью OR v.код_степени IS NOT NULL OR v.код_звания IS NOT NULL)
    ORDER BY v.фамилия, v.имя, v.отчество;
$$;

-- 3.5 Сводные показатели для главной страницы
CREATE OR REPLACE FUNCTION fn_статистика()
RETURNS TABLE (показатель text, значение bigint)
LANGUAGE sql STABLE AS $$
    SELECT 'Сотрудников', count(*) FROM сотрудник
    UNION ALL SELECT 'Подразделений', count(*) FROM v_подразделение
    UNION ALL SELECT 'Преподавателей', count(*) FROM сотрудник s
              JOIN должность d ON d.код_должности = s.код_должности WHERE d.преподавательская
    UNION ALL SELECT 'С учёной степенью или званием', count(*) FROM сотрудник
              WHERE код_степени IS NOT NULL OR код_звания IS NOT NULL
    UNION ALL SELECT 'Телефонов', count(*) FROM телефон;
$$;

