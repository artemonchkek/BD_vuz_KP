-- 1.1 Контроль личной карточки сотрудника
CREATE OR REPLACE FUNCTION trg_сотрудник_проверка() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_тек_год  int := extract(year FROM current_date)::int;
    v_возраст  int;
    v_шаблон   text := '^[А-ЯЁа-яёA-Za-z]+([- ][А-ЯЁа-яёA-Za-z]+)*$';
BEGIN
    NEW.фамилия  := btrim(NEW.фамилия);
    NEW.имя      := btrim(NEW.имя);
    NEW.отчество := nullif(btrim(coalesce(NEW.отчество, '')), '');
    NEW.вуз_по_диплому := nullif(btrim(coalesce(NEW.вуз_по_диплому, '')), '');

    IF NEW.фамилия = '' OR NEW.фамилия !~ v_шаблон THEN
        RAISE EXCEPTION 'Фамилия должна состоять из букв (допускаются дефис и пробел)'
              USING ERRCODE = 'P0001', HINT = 'фамилия';
    END IF;
    IF NEW.имя = '' OR NEW.имя !~ v_шаблон THEN
        RAISE EXCEPTION 'Имя должно состоять из букв (допускаются дефис и пробел)'
              USING ERRCODE = 'P0001', HINT = 'имя';
    END IF;
    IF NEW.отчество IS NOT NULL AND NEW.отчество !~ v_шаблон THEN
        RAISE EXCEPTION 'Отчество должно состоять из букв'
              USING ERRCODE = 'P0001', HINT = 'отчество';
    END IF;

    IF NEW.год_рождения < 1940 OR NEW.год_рождения > v_тек_год - 18 THEN
        RAISE EXCEPTION 'Неверно введен год рождения! Допустимый диапазон: 1940–%', v_тек_год - 18
              USING ERRCODE = 'P0001', HINT = 'год_рождения';
    END IF;

    v_возраст := v_тек_год - NEW.год_рождения;
    IF NEW.общий_стаж < 0 OR NEW.общий_стаж > v_возраст - 14 THEN
        RAISE EXCEPTION 'Общий стаж работы не может превышать возраст сотрудника минус 14 лет (допустимо от 0 до %)',
              greatest(v_возраст - 14, 0)
              USING ERRCODE = 'P0001', HINT = 'общий_стаж';
    END IF;

    IF NEW.стаж_нпр < 0 OR NEW.стаж_нпр > NEW.общий_стаж THEN
        RAISE EXCEPTION 'Стаж научно-педагогической работы не может быть отрицательным или превышать общий стаж (общий стаж: %)',
              NEW.общий_стаж
              USING ERRCODE = 'P0001', HINT = 'стаж_нпр';
    END IF;

    IF num_nonnulls(NEW.номер_отдела, NEW.код_факультета, NEW.номер_кафедры, NEW.номер_лаборатории) <> 1 THEN
        RAISE EXCEPTION 'Сотрудник должен быть закреплён ровно за одним подразделением'
              USING ERRCODE = 'P0001', HINT = 'подразделение';
    END IF;

    RETURN NEW;
END $$;

CREATE TRIGGER tr_сотрудник_проверка
    BEFORE INSERT OR UPDATE ON сотрудник
    FOR EACH ROW EXECUTE FUNCTION trg_сотрудник_проверка();

-- 1.2 Контроль номера телефона
CREATE OR REPLACE FUNCTION trg_телефон_проверка() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_цифр int;
BEGIN
    NEW.номер := regexp_replace(btrim(NEW.номер), '\s+', ' ', 'g');
    v_цифр := length(regexp_replace(NEW.номер, '\D', '', 'g'));
    IF NEW.номер !~ '^\+?[0-9][0-9() -]*[0-9]$' OR v_цифр < 5 OR v_цифр > 15 THEN
        RAISE EXCEPTION 'Неверный формат телефона «%»: допускаются цифры, пробел, дефис, скобки и «+» в начале (5–15 цифр)',
              NEW.номер
              USING ERRCODE = 'P0001', HINT = 'телефон';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER tr_телефон_проверка
    BEFORE INSERT OR UPDATE ON телефон
    FOR EACH ROW EXECUTE FUNCTION trg_телефон_проверка();

-- 1.3 Запрет удаления подразделения, в котором есть дочерние подразделения
--     или сотрудники (вместо системной ошибки внешнего ключа)
CREATE OR REPLACE FUNCTION trg_подразделение_удаление() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_дочерних  int := 0;
    v_сотр      int := 0;
    v_название  text;
    v_что       text;
BEGIN
    CASE TG_TABLE_NAME
    WHEN 'отдел' THEN
        SELECT count(*) INTO v_дочерних FROM факультет WHERE номер_отдела = OLD.номер_отдела;
        SELECT count(*) INTO v_сотр FROM сотрудник WHERE номер_отдела = OLD.номер_отдела;
        v_название := OLD.название_отдела; v_что := 'отдел';
    WHEN 'факультет' THEN
        SELECT count(*) INTO v_дочерних FROM кафедра WHERE код_факультета = OLD.код_факультета;
        SELECT count(*) INTO v_сотр FROM сотрудник WHERE код_факультета = OLD.код_факультета;
        v_название := OLD.название_факультета; v_что := 'факультет';
    WHEN 'кафедра' THEN
        SELECT count(*) INTO v_дочерних FROM лаборатория WHERE номер_кафедры = OLD.номер_кафедры;
        SELECT count(*) INTO v_сотр FROM сотрудник WHERE номер_кафедры = OLD.номер_кафедры;
        v_название := OLD.название_кафедры; v_что := 'кафедру';
    WHEN 'лаборатория' THEN
        SELECT count(*) INTO v_сотр FROM сотрудник WHERE номер_лаборатории = OLD.номер_лаборатории;
        v_название := OLD.название_лаборатории; v_что := 'лабораторию';
    END CASE;

    IF v_дочерних > 0 OR v_сотр > 0 THEN
        RAISE EXCEPTION 'Нельзя удалить % «%»: подчинённых подразделений — %, сотрудников — %. Сначала перенесите или удалите их.',
              v_что, v_название, v_дочерних, v_сотр
              USING ERRCODE = 'P0001';
    END IF;
    RETURN OLD;
END $$;

CREATE TRIGGER tr_отдел_удаление       BEFORE DELETE ON отдел       FOR EACH ROW EXECUTE FUNCTION trg_подразделение_удаление();
CREATE TRIGGER tr_факультет_удаление   BEFORE DELETE ON факультет   FOR EACH ROW EXECUTE FUNCTION trg_подразделение_удаление();
CREATE TRIGGER tr_кафедра_удаление     BEFORE DELETE ON кафедра     FOR EACH ROW EXECUTE FUNCTION trg_подразделение_удаление();
CREATE TRIGGER tr_лаборатория_удаление BEFORE DELETE ON лаборатория FOR EACH ROW EXECUTE FUNCTION trg_подразделение_удаление();

